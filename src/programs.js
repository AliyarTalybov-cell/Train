function cutlerWeek(week) { // week — с нуля
  const cycle = Math.floor(week / 2) % 6, heavy = week % 2 === 0;
  const all = CUTLER_SETS[cycle].split(" "), sets = heavy ? all.slice(0, 28) : all.slice(28);
  let k = 0;
  return (heavy ? CUTLER_H : CUTLER_M).map(([focus, names]) => ({
    title: focus, focus: heavy ? "Тяжёлая неделя · отдых 3–4 мин" : "Умеренная неделя · отдых 2–3 мин",
    ex: names.map(raw => {
      const [name, ss] = raw.split("|"), [s, r] = sets[k++].split("x");
      return { n: [name], s: +s, r: r.replace("-", "–"), tip: ss ? (ss === "а" ? "Суперсет со следующим: без отдыха между ними" : "Суперсет с предыдущим") : "" };
    }),
  }));
}
